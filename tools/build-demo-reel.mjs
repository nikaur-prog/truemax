// Build the landing-page demo reel.
//
// Scans a handful of faces, writes downscaled images into public/demo/ and a
// generated module holding each face's landmark outline and real scores, so
// the reel animates instantly without running the model on page load.
//
// Seeded with US federal-government portraits, which are public domain — the
// reel ships inside the app, so anything with an attribution requirement
// would need per-image credit. Swap in any images you hold rights to.
import { chromium } from "playwright";
import { spawn } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import sharp from "sharp";

const APP_DIR = "/home/user/truemax";
const DATA = process.env.TM_DATA ?? new URL("../.calib/", import.meta.url).pathname;
const OUT_IMG = `${APP_DIR}/public/demo`;
mkdirSync(OUT_IMG, { recursive: true });

// name -> source file, all public domain (US government works)
const FACES = JSON.parse(readFileSync(DATA + "pop-manifest.json", "utf8"))
  .concat(JSON.parse(readFileSync(DATA + "manifest.json", "utf8")))
  .filter((r) => (process.env.TM_REEL ?? "Barack Obama,Michelle Obama,Kamala Harris,Bernie Sanders,Elizabeth Warren,Jerome Powell,Anthony Fauci,Nancy Pelosi")
    .split(",")
    .includes(r.name));

const server = spawn("npx", ["vite", "preview", "--port", "4205", "--strictPort"], { cwd: APP_DIR, stdio: "ignore" });
await new Promise((r) => setTimeout(r, 2500));
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });

const entries = [];
try {
  const page = await browser.newPage();
  await page.goto("http://localhost:4205/");
  await page.waitForSelector("#engine-status.ready", { timeout: 60000 });

  for (const { name, sex, file } of FACES) {
    const url = `data:image/jpeg;base64,${readFileSync(file).toString("base64")}`;
    const m = await page.evaluate(async ([u, s]) => {
      const r = await window.__truemaxMeasure(u, s);
      if (!r.faceFound) return null;
      return { overall: r.overall, pillars: r.pillars, lm: r.reelLandmarks, box: r.reelBox };
    }, [url, sex]);
    if (!m) {
      console.log(`skip ${name} — no face`);
      continue;
    }
    const slug = name.toLowerCase().replace(/[^a-z]+/g, "-");
    // Crop tight to the face and save small — this ships in the bundle
    const meta = await sharp(file).metadata();
    const pad = 0.34;
    const x = Math.max(0, Math.round((m.box.x - m.box.w * pad) * meta.width));
    const y = Math.max(0, Math.round((m.box.y - m.box.h * pad * 1.1) * meta.height));
    const w = Math.min(meta.width - x, Math.round(m.box.w * (1 + pad * 2) * meta.width));
    const h = Math.min(meta.height - y, Math.round(m.box.h * (1 + pad * 2.2) * meta.height));
    await sharp(file).extract({ left: x, top: y, width: w, height: h }).resize(420, 525, { fit: "cover" })
      .jpeg({ quality: 78 }).toFile(`${OUT_IMG}/${slug}.jpg`);

    // Landmarks re-expressed relative to the crop, so they line up on the
    // cropped image the reel actually displays
    const rel = m.lm.map(([lx, ly]) => [
      +(((lx * meta.width - x) / w)).toFixed(4),
      +(((ly * meta.height - y) / h)).toFixed(4),
    ]);
    entries.push({ name, sex, slug, overall: m.overall, pillars: m.pillars, points: rel });
    console.log(`${name.padEnd(20)} ${m.overall}`);
  }
} finally {
  await browser.close();
  server.kill();
}

writeFileSync(
  `${APP_DIR}/src/ui/demoReelData.ts`,
  `// GENERATED by tools/build-demo-reel.mjs — do not hand-edit.
//
// Real scans of public-domain portraits: the landing-page reel shows the
// engine's actual output, not a mock-up. Images live in public/demo/.
export interface ReelFace {
  name: string;
  sex: "male" | "female";
  slug: string;
  overall: number;
  points: Array<[number, number]>;
}

export const REEL: ReelFace[] = ${JSON.stringify(
    entries.map((e) => ({ name: e.name, sex: e.sex, slug: e.slug, overall: e.overall, points: e.points })),
  )};
`,
);
console.log(`\nwrote ${entries.length} reel faces`);
process.exit(0);
